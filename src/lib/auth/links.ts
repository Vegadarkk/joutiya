import "server-only";
import type { Locale } from "@/config/site";
import { serverEnv } from "@/lib/env";
import { auth } from "@/lib/firebase/admin";
import { HttpError } from "@/lib/http/errors";
import { logger } from "@/lib/logging/logger";

// Links of the auth mails (§6 "Inscription par e-mail", PLAN): the Admin SDK generates the action
// code, Joutiya builds its own /action link around it and sends it with its own template. Firebase
// never e-mails anyone.

export type ActionMode = "verifyEmail" | "resetPassword";

export function siteUrl(): string {
  return serverEnv().SITE_URL.replace(/\/+$/, "");
}

export function pageUrl(locale: Locale, segment: string): string {
  return `${siteUrl()}/${locale}/${segment}`;
}

export function actionUrl(locale: Locale, mode: ActionMode, oobCode: string): string {
  return `${pageUrl(locale, "action")}?mode=${mode}&oobCode=${encodeURIComponent(oobCode)}`;
}

/** The oobCode of a link generated by the Admin SDK. */
export function oobCodeOf(link: string): string {
  let code: string | null = null;
  try {
    code = new URL(link).searchParams.get("oobCode");
  } catch {
    code = null;
  }
  if (!code) {
    logger.error("action link without oobCode");
    throw new HttpError(503, "unavailable", "action link unavailable");
  }
  return code;
}

export async function verificationActionUrl(email: string, locale: Locale): Promise<string> {
  const link = await auth().generateEmailVerificationLink(email, { url: pageUrl(locale, "action") });
  return actionUrl(locale, "verifyEmail", oobCodeOf(link));
}

export async function resetActionUrl(email: string, locale: Locale): Promise<string> {
  const link = await auth().generatePasswordResetLink(email, { url: pageUrl(locale, "action") });
  return actionUrl(locale, "resetPassword", oobCodeOf(link));
}
