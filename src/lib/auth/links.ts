import "server-only";
import type { Locale } from "@/config/site";
import { serverEnv } from "@/lib/env";
import type { ActionLinkRequest } from "@/lib/mail/types";
import { auth } from "@/lib/firebase/admin";
import { HttpError } from "@/lib/http/errors";
import { logger } from "@/lib/logging/logger";

// Links of the auth mails (§6 "Inscription par e-mail", PLAN): the Admin SDK generates the action
// code, Joutiya builds its own /action link around it and sends it with its own template. Firebase
// never e-mails anyone. The queue holds only the link request: the worker generates the code when
// it delivers the mail, so no live code waits in Valkey (audit B3-12).

export type ActionMode = "verifyEmail" | "resetPassword";

export function siteUrl(): string {
  return serverEnv().SITE_URL.replace(/\/+$/, "");
}

export function pageUrl(locale: Locale, segment: string): string {
  return `${siteUrl()}/${locale}/${segment}`;
}

/** The /action link request of a member mail: the code is generated at delivery (src/lib/mail/deliver.ts). */
export function actionLinkRequest(locale: Locale, mode: ActionMode): ActionLinkRequest {
  const page = pageUrl(locale, "action");
  return { action: mode, url: `${page}?mode=${mode}`, continueUrl: page };
}

/** The oobCode of a link generated by the Admin SDK. */
export function oobCodeOf(link: string): string {
  let code: string | null = null;
  try {
    code = new URL(link).searchParams.get("oobCode");
  } catch {
    code = null;
  }
  if (!code) {
    logger.error("action link without oobCode");
    throw new HttpError(503, "unavailable", "action link unavailable");
  }
  return code;
}

/**
 * Generates the action code for `email` and returns the request's page with it, or null when no
 * Auth account has this address any more (purged sign-up, deleted staff): the mail is dropped.
 */
export async function generateActionUrl(email: string, request: ActionLinkRequest): Promise<string | null> {
  let link: string;
  try {
    link =
      request.action === "verifyEmail"
        ? await auth().generateEmailVerificationLink(email, { url: request.continueUrl })
        : await auth().generatePasswordResetLink(email, { url: request.continueUrl });
  } catch (error) {
    if ((error as { code?: string }).code === "auth/user-not-found") return null;
    throw error;
  }
  const url = new URL(request.url);
  url.searchParams.set("oobCode", oobCodeOf(link));
  return url.toString();
}
