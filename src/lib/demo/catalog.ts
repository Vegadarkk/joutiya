export interface DemoSeller {
  key: string;
  name: string;
  type: "individual" | "pro";
  city: string;
  bio?: string;
  locale?: "fr" | "ar" | "rif";
  /** Pro shop sector: an agency or a car rental agency gets its specialised storefront. */
  sector?: "real_estate" | "car_rental";
  /** An agency's fee schedule, shown on its storefront. */
  feeSchedule?: string;
}

export interface DemoEntry {
  key: string;
  sub: string;
  seller: string;
  city: string;
  /** Age of the listing in days at seed time (sort order, "publié il y a"). */
  days: number;
  title: string;
  description: string;
  /** Integer MAD; null = "à discuter" (subcategories with priceOptional). */
  price: number | null;
  negotiable?: boolean;
  donation?: boolean;
  condition?: Condition;
  attributes: Record<string, string | number | boolean | string[]>;
  /** Pexels photo ids, display order. */
  photos: string[];
  /** Car rentals: blocked periods as [first, last] days after the seed day (rental pack §3). */
  rentalBlocked?: [number, number][];
  /** Pro catalogue (catalogue §2-3): combinations with their stock and price, or the declared stock. */
  variants?: ListingVariants;
  stock?: number;
}

