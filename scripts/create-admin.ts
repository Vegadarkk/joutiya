// Creates the first back-office admin (§6 "Personnel": the first admin is created once, by a local
// script, with the owner's agreement). Runs from the owner's machine with his own Google
// credentials (`gcloud auth application-default login`), or against the local emulators when
// FIREBASE_AUTH_EMULATOR_HOST is set (no credentials needed then).
//
//   APP_ENV=prod node scripts/create-admin.ts --email <e-mail> --name <name> [--apply]
//
// For staging and prod, FIREBASE_PROJECT_ID, SITE_URL and ADMIN_HOST follow from infra/targets.json
// and the hosts of §1 (derivedValues of scripts/vm-env.ts: the values the VM itself gets) unless
// set in the environment, so no --env-file is needed (the owner's .env.local holds dev values). A
// FIREBASE_PROJECT_ID that is set must be the project recorded for APP_ENV in infra/targets.json
// (§9, scripts/assert-target.ts), and SITE_URL must be https there. Dev keeps the environment as
// given; against the emulators APP_ENV defaults to dev and a demo-* project passes. Dry run by
// default: prints the planned steps and exits 0. With --apply:
//   1. getUserByEmail: reused only when it is already a staff account (staff claims, or a staff/{uid}
//      entry: a revoked admin), refused for any other existing account (it keeps its own password),
//      else createUser({ email, emailVerified: true, displayName });
//   2. staff/{uid} upsert with invitedBy "script", BEFORE the claims: a run that stops here leaves
//      an entry without rights, never an admin the roster does not show;
//   3. setCustomUserClaims({ role: "admin", v: 2 }), refresh tokens revoked;
//   4. generatePasswordResetLink(email, { url: <ADMIN_ORIGIN>/connexion }), then prints ONE line:
//      <ADMIN_ORIGIN>/connexion?mode=setPassword&oobCode=...
// That URL is the only way to set the first password without a mail transport: open it behind
// Cloudflare Access with the same Google account, within the hour (Firebase action codes expire);
// run the script again for a fresh link. Nothing else from the environment is printed.
// ADMIN_ORIGIN is SITE_URL's scheme and port on ADMIN_HOST, like expectedOrigin("admin") in
// src/lib/security/origin.ts (re-implemented here: that module is server-only).

import { readFileSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { assertTargets, validateTargets, type Targets } from "./assert-target.ts";
import { DEPLOYED_ENVS, derivedValues, type DeployedEnv } from "./vm-env.ts";

export interface CreateAdminArgs {
  email: string;
  name: string;
  apply: boolean;
}

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const USAGE = "usage: scripts/create-admin.ts --email <e-mail> --name <name> [--apply]";

export function parseCli(argv: readonly string[]): CreateAdminArgs {
  const { values } = parseArgs({
    args: [...argv],
    options: { email: { type: "string" }, name: { type: "string" }, apply: { type: "boolean", default: false } },
    strict: true,
  });
  const email = values.email?.trim().toLowerCase() ?? "";
  const name = values.name?.trim() ?? "";
  if (!EMAIL.test(email) || email.length > 254) throw new Error(USAGE);
  if (name.length < 2 || name.length > 40) throw new Error(`--name must have 2 to 40 characters\n${USAGE}`);
  return { email, name, apply: values.apply === true };
}

/** Origin of the back office: SITE_URL's scheme and port on ADMIN_HOST (SITE_URL itself without ADMIN_HOST). */
export function adminOrigin(siteUrl: string, adminHost: string | undefined): string {
  const site = new URL(siteUrl);
  const host = (adminHost ?? "").trim().toLowerCase().replace(/:\d+$/, "").replace(/\.$/, "");
  if (!host) return site.origin;
  return `${site.protocol}//${host}${site.port ? `:${site.port}` : ""}`;
}

export function setPasswordUrl(origin: string, oobCode: string): string {
  return `${origin}/connexion?mode=setPassword&oobCode=${encodeURIComponent(oobCode)}`;
}

/** The oobCode of a link generated by the Admin SDK (Firebase's own page is never used). */
export function oobCodeOf(link: string): string {
  const code = new URL(link).searchParams.get("oobCode");
  if (!code) throw new Error("the generated link carries no oobCode");
  return code;
}

/**
 * Why FIREBASE_PROJECT_ID cannot be used: not the project recorded for APP_ENV in infra/targets.json
 * (or no APP_ENV to look it up). Empty when it matches. The configured value is never printed.
 */
export function projectErrors(targets: unknown, env: { APP_ENV?: string | undefined; FIREBASE_PROJECT_ID?: string | undefined }): string[] {
  const fileErrors = validateTargets(targets);
  if (fileErrors.length > 0) return fileErrors.map((error) => `infra/targets.json: ${error}`);
  return assertTargets(targets as Targets, { APP_ENV: env.APP_ENV, FIREBASE_PROJECT_ID: env.FIREBASE_PROJECT_ID });
}

export interface RunSettings {
  projectId: string;
  /** Origin of the back office the set-password link points to. */
  origin: string;
  emulated: boolean;
}

const isDeployedEnv = (env: string | undefined): env is DeployedEnv => (DEPLOYED_ENVS as readonly string[]).includes(env ?? "");

/**
 * Project and admin origin of the run. For staging and prod they follow from infra/targets.json and
 * the hosts of §1 (derivedValues of scripts/vm-env.ts) unless set in the environment; a set
 * FIREBASE_PROJECT_ID must match the registry (projectErrors) and SITE_URL must be https, so a dev
 * .env.local loaded by mistake never yields a localhost link. Dev keeps the environment as given.
 * Throws with the names of what is wrong; no configured value is ever printed.
 */
export function resolveSettings(env: Record<string, string | undefined>, targets: unknown): RunSettings {
  const fileErrors = validateTargets(targets);
  if (fileErrors.length > 0) throw new Error(fileErrors.map((error) => `infra/targets.json: ${error}`).join("\n"));
  const emulated = Boolean(env["FIREBASE_AUTH_EMULATOR_HOST"]);
  const appEnv = env["APP_ENV"]?.trim() || (emulated ? "dev" : undefined);
  const derived = isDeployedEnv(appEnv) ? derivedValues(appEnv, targets as Targets) : {};
  const projectId = env["FIREBASE_PROJECT_ID"]?.trim() || derived["FIREBASE_PROJECT_ID"];
  if (!projectId) {
    throw new Error(
      isDeployedEnv(appEnv)
        ? `FIREBASE_PROJECT_ID is required: environments.${appEnv}.firebase.projectId is not recorded in infra/targets.json`
        : "FIREBASE_PROJECT_ID is required (derived from infra/targets.json for APP_ENV staging or prod only)",
    );
  }
  const problems = projectErrors(targets, { APP_ENV: appEnv, FIREBASE_PROJECT_ID: projectId });
  if (problems.length > 0) throw new Error(problems.join("\n"));
  const siteUrl = env["SITE_URL"]?.trim() || derived["SITE_URL"] || "http://localhost:3000";
  const origin = adminOrigin(siteUrl, env["ADMIN_HOST"]?.trim() || derived["ADMIN_HOST"]);
  if (isDeployedEnv(appEnv) && !origin.startsWith("https://")) throw new Error(`SITE_URL must be https when APP_ENV=${appEnv} (unset it to use the hosts of infra/targets.json)`);
  return { projectId, origin, emulated };
}

export interface ExistingAccount {
  /** `role` custom claim of the Auth record, whatever its value. */
  role: unknown;
  /** staff/{uid} exists (a revoked member keeps its entry while its claims are cleared). */
  rosterExists: boolean;
}

/** Why an existing Auth account cannot become the first admin; null when it already is a staff account. */
export function existingAccountProblem(account: ExistingAccount): string | null {
  if (account.role === "admin" || account.role === "moderator" || account.rosterExists) return null;
  return "a Joutiya account already exists with this e-mail (member, or a sign-up never confirmed) and keeps its own password: staff accounts are separate (§6), use another address";
}

export interface PlanInput {
  args: CreateAdminArgs;
  projectId: string;
  origin: string;
  emulated: boolean;
}

export function planSteps({ args, projectId, origin, emulated }: PlanInput): string[] {
  return [
    `Project ${projectId} (${emulated ? "Auth emulator" : "Application Default Credentials"}), admin origin ${origin}`,
    `1. Auth account ${args.email}: reuse it if it is already staff (claims or staff/<uid>), refuse any other existing account, else create it verified with the name "${args.name}"`,
    `2. staff/<uid> = { email, displayName, role: "admin", invitedBy: "script", createdAt } (before the claims)`,
    `3. Custom claims { role: "admin", v: 2 }, refresh tokens revoked`,
    `4. Password-reset link for ${args.email} (continue URL ${origin}/connexion)`,
    `Output: ${origin}/connexion?mode=setPassword&oobCode=<code>`,
    "Dry run: nothing changed. Add --apply to run these steps.",
  ];
}

function readTargets(): unknown {
  return JSON.parse(readFileSync(fileURLToPath(new URL("../infra/targets.json", import.meta.url)), "utf8"));
}

async function main(): Promise<void> {
  const args = parseCli(process.argv.slice(2));
  const { projectId, origin, emulated } = resolveSettings(process.env, readTargets());
  if (!args.apply) {
    for (const line of planSteps({ args, projectId, origin, emulated })) console.log(line);
    return;
  }

  const { applicationDefault, initializeApp } = await import("firebase-admin/app");
  const { getAuth } = await import("firebase-admin/auth");
  const { getFirestore } = await import("firebase-admin/firestore");
  const app = initializeApp({ projectId, ...(emulated ? {} : { credential: applicationDefault() }) });
  const auth = getAuth(app);
  const staff = getFirestore(app).collection("staff");

  const existing = await auth.getUserByEmail(args.email).catch(() => null);
  if (existing) {
    const problem = existingAccountProblem({ role: existing.customClaims?.["role"], rosterExists: (await staff.doc(existing.uid).get()).exists });
    if (problem) throw new Error(problem);
  }
  const uid = existing?.uid ?? (await auth.createUser({ email: args.email, emailVerified: true, displayName: args.name })).uid;
  if (existing?.disabled) await auth.updateUser(uid, { disabled: false });

  // Roster first: stopping after this step leaves an entry without rights, never the reverse.
  const ref = staff.doc(uid);
  const current = await ref.get();
  const createdAt: unknown = current.exists ? current.get("createdAt") : new Date();
  await ref.set({ email: args.email, displayName: args.name, role: "admin", invitedBy: "script", createdAt });
  await auth.setCustomUserClaims(uid, { role: "admin", v: 2 });
  await auth.revokeRefreshTokens(uid);

  const link = await auth.generatePasswordResetLink(args.email, { url: `${origin}/connexion` });
  console.log(setPasswordUrl(origin, oobCodeOf(link)));
}

const self = fileURLToPath(import.meta.url);
if (/[\\/]create-admin\.(?:ts|mjs)$/.test(self) && process.argv[1] !== undefined && realpathSync(process.argv[1]) === self) {
  main().catch((error: unknown) => {
    console.error(`create-admin: ${(error as Error).message}`);
    process.exit(1);
  });
}
